/**
 * Glob 模式工具
 *
 * 提供 Glob 模式到正则表达式的转换，以及文件路径匹配功能。
 * 支持：
 * - `*` 匹配路径中除 `/` 外的任意字符
 * - `**` 匹配任意层级路径（跨目录）
 * - `?` 匹配单个非 `/` 字符
 * - `[...]` 字符类匹配
 * - 以 `/` 开头的模式表示从项目根目录开始匹配
 * - 正则缓存，避免重复转换
 */
/** 正则缓存，键为 glob 模式字符串，值为对应的 RegExp */
const 正则缓存 = new Map<string, RegExp>()

/**
 * 将 Glob 模式转换为正则表达式
 * 从文件扫描器.ts 中提取并增强（支持 `/` 开头锚定、跨目录匹配）
 */
export function glob模式转正则(模式: string): RegExp {
  // 检查缓存
  const 缓存命中 = 正则缓存.get(模式)
  if (缓存命中) return 缓存命中

  let 是否需要从根开始 = false
  let 待处理 = 模式

  // 处理以 / 开头的模式，标记为从根目录开始匹配
  if (待处理.startsWith('/')) {
    是否需要从根开始 = true
    待处理 = 待处理.slice(1)
  }

  // 处理以目录分隔符结尾的模式（如 src/**）
  if (待处理.endsWith('/')) {
    待处理 = 待处理.slice(0, -1)
  }

  let 正则字符串 = ''

  let i = 0
  while (i < 待处理.length) {
    const c = 待处理[i]!

    if (c === '*' && 待处理[i + 1] === '*') {
      // ** 匹配任意层级（包括零层），可跨目录
      正则字符串 += '.*'
      i += 2
      // 跳过紧随 ** 之后的 /
      if (i < 待处理.length && 待处理[i] === '/') i++
    } else if (c === '*') {
      // * 匹配当前层级中除 / 外的任意字符
      正则字符串 += '[^/]*'
      i++
    } else if (c === '?') {
      // ? 匹配单个非 / 字符
      正则字符串 += '[^/]'
      i++
    } else if (c === '[') {
      // [...] 字符类，原样保留但需要转义其中的特殊正则字符
      const 闭括号 = 待处理.indexOf(']', i)
      if (闭括号 === -1) {
        正则字符串 += '\\' + c
        i++
      } else {
        const 片段 = 待处理.slice(i + 1, 闭括号)
        // 在字符类内，仅需转义少数正则元字符
        const 已转义 = 片段.replace(/\\/g, '\\\\').replace(/\]/g, '\\]').replace(/\^/g, '\\^')
        正则字符串 += '[' + 已转义 + ']'
        i = 闭括号 + 1
      }
    } else if (/[.+^${}()|\\]/.test(c)) {
      // 正则特殊字符需要转义
      正则字符串 += '\\' + c
      i++
    } else {
      正则字符串 += c
      i++
    }
  }

  // 构建完整正则
  let 完整正则: string
  if (是否需要从根开始) {
    // 以 / 开头表示从根目录开始匹配
    完整正则 = '^' + 正则字符串 + '(?:/.*)?$'
  } else if (模式.includes('**') || 模式.startsWith('**')) {
    // 包含 ** 的模式匹配任意位置
    完整正则 = 正则字符串
  } else if (模式.startsWith('*')) {
    // 以 * 开头但不含 ** → 匹配路径末尾的文件名
    完整正则 = '(?:^|.*/)' + 正则字符串 + '$'
  } else if (模式.startsWith('.') && !模式.includes('*') && !模式.includes('?')) {
    // 纯文件名模式（如 .clineignore）→ 匹配路径中任意位置出现的该文件名
    完整正则 = '(?:^|.*/)?' + 正则字符串 + '$'
  } else {
    // 默认：精确匹配
    完整正则 = '^' + 正则字符串 + '(?:/.*)?$'
  }

  const regex = new RegExp(完整正则)
  正则缓存.set(模式, regex)
  return regex
}

/**
 * 判断文件相对路径是否匹配给定的 Glob 模式
 * @param 文件相对路径 相对于项目根目录的文件路径（使用正斜杠 /）
 * @param 模式 Glob 模式字符串
 * @returns 是否匹配
 */
export function 是否匹配Glob模式(文件相对路径: string, 模式: string): boolean {
  // 统一使用正斜杠
  const 标准化路径 = 文件相对路径.replace(/\\/g, '/')
  const regex = glob模式转正则(模式)
  return regex.test(标准化路径)
}

/**
 * 从模式列表中判断文件是否至少匹配一个模式
 * 使用 some 方法短路退出，提高性能
 * @param 文件相对路径 相对于项目根目录的文件路径
 * @param 模式列表 Glob 模式列表
 * @returns 是否匹配任意一个模式
 */
export function 是否匹配任意模式(文件相对路径: string, 模式列表: string[]): boolean {
  // 限制模式列表最大 200 条
  const 有效列表 = 模式列表.slice(0, 200)
  return 有效列表.some((模式) => 是否匹配Glob模式(文件相对路径, 模式))
}

/**
 * 清空正则缓存（主要用于测试）
 */
export function 清空Glob缓存(): void {
  正则缓存.clear()
}
