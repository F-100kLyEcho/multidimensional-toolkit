import { defineStore } from 'pinia'
import { ref } from 'vue'

/** 多维记忆数据（第一版：id + 场景 + 标题? + 内容 + 创建时间） */
export interface 多维记忆数据 {
  id: string
  场景: string
  标题?: string
  内容: string
  创建时间: number
}

/** 生成示例数据（第一版：外观演示，暂不落盘） */
function 生成示例(): 多维记忆数据[] {
  const 现在 = Date.now()
  return [
    { id: '示例1', 场景: '编程，效率原则', 标题: '压缩重复操作', 内容: '把日常重复操作压缩到最少步骤。', 创建时间: 现在 - 1000 * 60 * 60 * 25 },
    { id: '示例2', 场景: '编程，笔记软件开发', 内容: '记忆泡：写一条，发给自己。\n先外观后功能，边开发边想。', 创建时间: 现在 - 1000 * 60 * 60 * 3 },
    { id: '示例3', 场景: '编程', 内容: '第一条真实记录就快来了。', 创建时间: 现在 - 1000 * 60 * 8 },
    { id: '示例4', 场景: '读书，《认知觉醒》', 标题: '舒适区边缘', 内容: '在舒适区边缘学习，难度适中，成长最快。太简单无聊，太难放弃。', 创建时间: 现在 - 1000 * 60 * 60 * 48 },
    { id: '示例5', 场景: '生活，健身', 内容: '每周三次力量训练，重点复合动作：深蹲、硬拉、卧推。', 创建时间: 现在 - 1000 * 60 * 60 * 72 },
    { id: '示例6', 场景: '工作，周会', 标题: '本周待办', 内容: '1. 完成记忆模块外观\n2. 接入数据落盘\n3. 浮岛拖拽优化', 创建时间: 现在 - 1000 * 60 * 30 },
  ]
}

export const 使用多维记忆仓库 = defineStore('多维记忆仓库', () => {
  const 列表 = ref<多维记忆数据[]>(生成示例())

  /** 新增一条多维记忆（第一版仅内存，落盘在后续版本接入） */
  function 发送(数据: { 场景: string; 标题?: string; 内容: string }) {
    const 文本 = 数据.内容.trim()
    if (!文本) return
    列表.value.push({
      id: `${Date.now()}-${Math.random().toString(36).slice(2, 8)}`,
      场景: 数据.场景 || '编程',
      标题: 数据.标题?.trim() || undefined,
      内容: 文本,
      创建时间: Date.now(),
    })
  }

  return { 列表, 发送 }
})
